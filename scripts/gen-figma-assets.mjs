// gen-figma-assets.mjs — inline the HCT Semantic Binder plugin into the app.
//
// The figma-plugin cell (figma/binder/figma-semantic-binder/) is the single source
// of truth; this generates ui-app/figma-plugin-assets.js so the tool can HAND the plugin
// to the user as a download (the live raw->semantic alias cascade native JSON import
// can't do). Regenerate after editing the plugin:  node gen-figma-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const PDIR = `${HERE}/../figma/binder/figma-semantic-binder`;
const manifest = readFileSync(`${PDIR}/manifest.json`, "utf8");
const code = readFileSync(`${PDIR}/code.js`, "utf8");

// bundlesafe (#492 real incident, moved here from a test/figma/binder.mjs gate per review): `code` below
// gets embedded WHOLE — every line, comments included — as a single JS string (JSON.stringify) inside
// src/ui/figma-plugin-assets.js, which scripts/bundle.mjs then splices into the web app's own SINGLE
// inline <script> block (dist/ultimate-tokens.html). A closing-script-tag substring ANYWHERE in `code`
// closes THAT enclosing tag early in the bundled HTML, silently truncating and corrupting every line of
// app JS after it — found live: confirmAdopt's inline figma.showUI() HTML needed a literal closing
// script tag to close its OWN embedded <script> block at runtime inside Figma; writing it unescaped
// broke the web app build, surfacing only downstream as `npm run smoke`'s real-Chrome "gallery boots" /
// "openCategory is not a function" (no browser in `npm test`, so nothing caught it there). The regex is
// case-insensitive and matches any real closing tag shape (`</script>`, `</SCRIPT >`, `</script/>`, a
// trailing newline before `>`) — not just the one literal spelling — since an HTML parser in raw-text
// mode inside <script> honors all of those as the close. Catching it HERE, at the generator, is the
// earliest possible point: this script is the FIRST step of both `npm test` and `npm run build`, so a
// violation fails the run immediately, pointing straight at the actual cause, before any downstream
// artifact (figma-plugin-assets.js, the bundled HTML) is ever written.
if (/<\/script[\s/>]/i.test(code)) {
  throw new Error(
    'gen-figma-assets: figma/binder/figma-semantic-binder/code.js contains a closing <script> tag as a literal, contiguous substring (in code OR a comment) — this file is embedded whole as a JS string inside the web app\'s own <script> block. Write it split, e.g. "<\\/script>" (a no-op JS escape that evaluates to the identical runtime string), so it never appears as this dangerous substring in source.',
  );
}

const out = `// GENERATED by gen-figma-assets.mjs from figma/binder/figma-semantic-binder/ — DO NOT EDIT.
// The Color Tokens Semantic Binder plugin (manifest + runtime), inlined so the tool can hand it to
// the user as a download. Single source of truth is the figma-plugin cell; regenerate with
//   node gen-figma-assets.mjs
export const FIGMA_PLUGIN = {
  name: ${JSON.stringify(JSON.parse(manifest).name)},
  manifest: ${JSON.stringify(manifest)},
  code: ${JSON.stringify(code)},
};
`;
writeFileSync(`${HERE}/../src/ui/figma-plugin-assets.js`, out);
console.log("wrote src/ui/figma-plugin-assets.js", (out.length / 1024).toFixed(1) + " KB");
